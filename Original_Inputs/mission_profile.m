function phases = mission_profile(A, cruiseDuration_s)

% This function creates the different phases of the UAV mission.
% It stores the time, speed and altitude information for each phase.

% If cruise duration is not given, keep it as zero
if nargin < 2 || isempty(cruiseDuration_s) || isnan(cruiseDuration_s)
    cruiseDuration_s = 0;
end

% Calculate time required to reach cruise altitude
climbDuration = A.cruiseAltitude / A.climbRate;

%% Takeoff

phases(1) = struct( ...
    'name','Takeoff', ...
    'duration',A.takeoffDuration, ...
    'mode','level', ...
    'altStart',0, ...
    'altEnd',0, ...
    'speed',A.takeoffSpeed, ...
    'climbRate',0);

%% Climb

phases(2) = struct( ...
    'name','Climb', ...
    'duration',climbDuration, ...
    'mode','climb', ...
    'altStart',0, ...
    'altEnd',A.cruiseAltitude, ...
    'speed',A.climbSpeed, ...
    'climbRate',A.climbRate);

%% Cruise

phases(3) = struct( ...
    'name','Cruise', ...
    'duration',cruiseDuration_s, ...
    'mode','level', ...
    'altStart',A.cruiseAltitude, ...
    'altEnd',A.cruiseAltitude, ...
    'speed',A.cruiseSpeed, ...
    'climbRate',0);

%% Loiter

phases(4) = struct( ...
    'name','Loiter', ...
    'duration',A.loiterDuration, ...
    'mode','level', ...
    'altStart',A.loiterAltitude, ...
    'altEnd',A.loiterAltitude, ...
    'speed',A.loiterSpeed, ...
    'climbRate',0);

%% Descent

phases(5) = struct( ...
    'name','Descent', ...
    'duration',A.descentDuration, ...
    'mode','descent', ...
    'altStart',A.descentAltitude, ...
    'altEnd',A.descentAltitude, ...
    'speed',A.descentSpeed, ...
    'climbRate',0);

end