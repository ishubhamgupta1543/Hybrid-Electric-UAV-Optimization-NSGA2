function optimizer()

% This function uses a Genetic Algorithm (GA)
% to find the design with maximum endurance.

% Load default aircraft data
A0 = assumptions();

%% Design variable limits

% x(1) = Climb rate (m/s)
% x(2) = Loiter time (minutes)

lb = [1.5, 60];
ub = [4.0, 180];

% GA minimizes the objective function,
% so endurance is multiplied by -1.
objFun = @(x) -evalDesign(A0, x);

%% GA settings

options = optimoptions('ga', ...
    'PopulationSize',30, ...
    'MaxGenerations',40, ...
    'Display','iter', ...
    'PlotFcn',@gaplotbestf);

%% Run optimization

[xOpt, fval] = ga(objFun,2,[],[],[],[],lb,ub,[],options);

%% Display results

fprintf('\n===== OPTIMIZATION RESULT =====\n');
fprintf('Best Climb Rate      : %.2f m/s\n',xOpt(1));
fprintf('Best Loiter Time     : %.1f min\n',xOpt(2));
fprintf('Maximum Endurance    : %.2f hours\n',-fval/3600);
fprintf('================================\n');

%% Run simulation with best design

A_opt = A0;

A_opt.climbRate = xOpt(1);
A_opt.loiterDuration = xOpt(2) * 60;

[endurance, result, battMass_kg, cruiseDuration_s] = ...
    evalDesignFull(A_opt); %#ok<ASGLU>

dashboard(result, A_opt, battMass_kg, cruiseDuration_s);

end


%% --------------------------------------------------------
function endurance = evalDesign(A0, x)

% This function evaluates one design generated by the GA.

A = A0;

A.climbRate = x(1);
A.loiterDuration = x(2) * 60;

try

    [endurance,~,battMass_kg,~] = evalDesignFull(A);

    if battMass_kg <= 0 || ~isfinite(endurance)
        endurance = -1e6;
    end

catch

    % Give a very low score for invalid designs
    endurance = -1e6;

end

end


%% --------------------------------------------------------
function [enduranceSeconds, result, battMass_kg, cruiseDuration_s] = evalDesignFull(A)

% This function performs the complete mission simulation
% for one design.

%% Find battery energy requirement

probeBattCapacity_Wh = 1e6;

probe = mission_sim(A, probeBattCapacity_Wh, 0);

dischargeMask = probe.Pbatt > 0;

if any(dischargeMask)

    dt_series = diff([0 probe.time]);

    dischargeEnergy_Wh = ...
        sum(probe.Pbatt(dischargeMask) .* dt_series(dischargeMask)) ...
        /3600 / A.battEfficiency;

else

    dischargeEnergy_Wh = 0;

end

nonCruiseFuel_kg = probe.totalFuel;

%% Calculate battery size

usableSoCFraction = A.SoC_initial - A.SoC_reserve;

battMass_kg = dischargeEnergy_Wh / ...
             (A.battSpecificEnergy * usableSoCFraction);

battCapacity_Wh = battMass_kg * A.battSpecificEnergy;

%% Calculate available cruise fuel

availableForFuel_kg = A.MTOW - A.OEW - A.payload - battMass_kg;

cruiseFuelBudget_kg = availableForFuel_kg - nonCruiseFuel_kg;

if cruiseFuelBudget_kg <= 0

    error('No fuel available for cruise.');

end

%% Calculate cruise time

cruiseFuelRate_kgps = engine_model(A, A.P_rated);

cruiseDuration_s = cruiseFuelBudget_kg / cruiseFuelRate_kgps;

%% Run complete mission

result = mission_sim(A, battCapacity_Wh, cruiseDuration_s);

enduranceSeconds = result.totalTime;

end