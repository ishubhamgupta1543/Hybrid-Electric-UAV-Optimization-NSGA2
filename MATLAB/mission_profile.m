function phases = mission_profile(A,cruiseDuration_s)
% Five original phases plus the missing transit to 3-km loiter altitude.
% No instantaneous altitude jumps are allowed.
if nargin < 2 || isempty(cruiseDuration_s)
    cruiseDuration_s = 0;
end
climbTime = A.cruiseAltitude/A.climbRate;
transitTime = (A.cruiseAltitude-A.loiterAltitude)/A.transitionDescentRate;
phases(1) = struct('name','Takeoff','duration',A.takeoffDuration, ...
    'mode','level','altStart',0,'altEnd',0,'speed',A.takeoffSpeed,'climbRate',0);
phases(2) = struct('name','Climb','duration',climbTime, ...
    'mode','climb','altStart',0,'altEnd',A.cruiseAltitude, ...
    'speed',A.climbSpeed,'climbRate',A.climbRate);
phases(3) = struct('name','Cruise','duration',cruiseDuration_s, ...
    'mode','level','altStart',A.cruiseAltitude,'altEnd',A.cruiseAltitude, ...
    'speed',A.cruiseSpeed,'climbRate',0);
phases(4) = struct('name','Transit Descent','duration',transitTime, ...
    'mode','descent','altStart',A.cruiseAltitude,'altEnd',A.loiterAltitude, ...
    'speed',A.descentSpeed,'climbRate',-A.transitionDescentRate);
phases(5) = struct('name','Loiter','duration',A.loiterDuration, ...
    'mode','level','altStart',A.loiterAltitude,'altEnd',A.loiterAltitude, ...
    'speed',A.loiterSpeed,'climbRate',0);
phases(6) = struct('name','Final Descent','duration',A.descentDuration, ...
    'mode','descent','altStart',A.loiterAltitude,'altEnd',0, ...
    'speed',A.descentSpeed,'climbRate',-A.loiterAltitude/A.descentDuration);
end
